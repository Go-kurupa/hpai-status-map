/** 国の文の出典名から、機関の名前を取り出す（もくじの「国の文 N つ: …」に使う） */
export function agencyOf(sourceTitle: string): string {
  if (sourceTitle.startsWith("家畜伝染病予防法")) return "法令";
  return /^(農林水産省|厚生労働省|環境省)/u.exec(sourceTitle)?.[1] ?? "その他";
}
